"""Stock Research Lab v1.6 beginner explanation layer.

No downloads, no guessed market data, and NO CHANGE to the v1.5 scoring rules.
Every numeric comparison uses exactly the same eligible (as-filed) history and
percentile algorithm as the automatic verdict.
"""
from __future__ import annotations

from dataclasses import dataclass
from investment_scorecard import _valuation


@dataclass(frozen=True)
class LensNote:
    key: str
    label: str
    nickname: str
    meaning: str
    current: float | None
    median: float | None
    percentile: float | None
    rating: int | None
    observations: int
    method: str
    as_of: str

    @property
    def relative_percent(self) -> float | None:
        if self.current is None or self.median is None or self.median <= 0:
            return None
        return (self.current / self.median - 1) * 100

    @property
    def position_text(self) -> str:
        if self.rating is None:
            return 'Not enough verified history'
        if self.rating >= 4:
            return 'Lower than usual'
        if self.rating <= 2:
            return 'Higher than usual'
        return 'Near its usual range'


_LENS_DESCRIPTIONS = (
    ('pe', 'P/E', 'Accounting profit',
     'How much investors pay for $1 of reported net income (profit after expenses).'),
    ('pocf', 'P/OCF', 'Operating cash',
     'How much investors pay for $1 of cash generated by normal operations, before capital spending.'),
    ('pfcf', 'P/FCF', 'Cash after investment',
     'How much investors pay for $1 of free cash flow—operating cash left after capital spending.'),
)


def lens_notes(histories, price_asof) -> tuple[LensNote, ...]:
    """Mirror the verdict's numeric eligibility and lookback WITHOUT changing it."""
    out = []
    for key, label, nickname, meaning in _LENS_DESCRIPTIONS:
        candidate = (histories or {}).get(key)
        rating, _, current, median, percentile, method, n, as_of = _valuation(
            {key: candidate} if candidate is not None else {}, price_asof
        )
        out.append(LensNote(key, label, nickname, meaning, current,
                            median, percentile, rating, n, method, as_of))
    return tuple(out)


def selection_explanation(notes, chosen_label):
    chosen = next((n for n in notes if n.label == chosen_label and n.rating is not None), None)
    if chosen is None:
        return ('The Lab does not have a recent enough, dependable valuation history. '
                'It will not make a positive buying call from missing data.')
    return (f'The automatic score uses **{chosen.label} ({chosen.nickname.lower()})**. '
            'The current rule tries P/FCF first, P/OCF second, then P/E. '
            'It selects the first with at least 24 valid monthly readings and a recent final observation. '
            'This is a published rule in our Lab, not proof that any one ratio is best for every company.')


def disagreement_explanation(notes, chosen_label):
    active = [n for n in notes if n.rating is not None]
    if len(active) < 2:
        return ('Only one (or no) valuation measure has enough reliable history for a comparison. '
                'That is a data limitation, not evidence that the other ratios are good or bad.')
    low = [n for n in active if n.rating >= 4]
    high = [n for n in active if n.rating <= 2]
    if low and high:
        low_labels = ', '.join(n.label for n in low)
        high_labels = ', '.join(n.label for n in high)
        return (f'**Important: the ratios disagree.** {low_labels} look lower than usual, '
                f'but {high_labels} look higher than usual, compared with each ratio\'s own past. '
                'Different ratios use different denominators. Accounting profit, operating cash, '
                'and cash remaining after capital expenditures do not always move together. '
                '**We cannot tell why they differ from these ratios alone.** '
                'Check earnings, cash flow, and capital spending in the filings before drawing a conclusion.')
    if all(n.rating >= 4 for n in active):
        return ('The available ratios all look relatively low versus their own history. '
                'That is a historical observation, not proof of a bargain.')
    if all(n.rating <= 2 for n in active):
        return ('The available ratios all look relatively high versus their own history. '
                'That is a historical observation, not proof of future losses.')
    return ('The ratios give somewhat different, mostly middle-range readings. '
            'They measure accounting profit and different types of cash, so do not expect '
            'them to match exactly. Historical ranges are not calculated fair values.')


def verdict_in_one_sentence(verdict):
    return {
        'BUY': ('BUY means the stock passed this Lab’s strict quality-and-historical-price screen. '
                'It does not guarantee a profit or establish a fair share price.'),
        'WATCH': ('WATCH means several fundamentals look strong, but at least one hurdle remains. '
                  'For a beginner, think “worth following, but not a clear pass on all tests.”'),
        'HOLD': ('HOLD means the evidence is mixed. It is a research label for an existing owner, '
                 'not a recommendation to purchase the stock.'),
        'PASS': ('PASS means the Lab cannot support a stronger assessment with the information '
                 'and rules available. It does not mean the company is definitely bad.'),
        'SELL': ('SELL is a warning that the Lab sees weak business measures and an unfavorable '
                 'historical multiple. It is not a personal instruction to sell.'),
    }.get(verdict, 'The Lab has no dependable verdict for this stock.')


def score_coverage(items):
    measured = sum(item.rating is not None for item in items)
    total = len(items)
    missing = [item.name for item in items if item.rating is None]
    return measured, total, missing


def next_steps(report):
    """Explain WHAT the rule requires, not predict a stock price."""
    ratings = {i.name: i.rating for i in report.items}
    missing = [i.name for i in report.items if i.rating is None]
    goals = []
    if report.verdict == 'BUY':
        goals.append('The current screen already clears its BUY thresholds. Double-check '
                     'recent SEC filings, industry risks, valuation assumptions and any recent changes. '
                     'A BUY label can change when prices or results change.')
    else:
        if report.valuation_rating is None:
            goals.append('First, obtain a recent eligible valuation history. Our rule needs '
                         'at least 24 valid monthly observations before it can support a BUY result.')
        elif report.valuation_rating < 4:
            goals.append(
                f'The selected **{report.valuation_lens} valuation scores {report.valuation_rating}/5**. '
                'The BUY rule requires **4/5 or 5/5**—roughly the lower 35% of this stock’s '
                'own measured multiples. This could change as stock price or earnings/cash flow '
                'changes; it is **not** a target price or a forecast.')
        if report.quality is None:
            goals.append('Gather comparable revenue, profit and cash-flow figures to establish '
                         'a reliable business score.')
        elif report.quality < 4:
            goals.append(f'Business fundamentals currently average **{report.quality:.2f}/5**; '
                         'the BUY rule requires **at least 4.00/5** across the measured categories. '
                         'Improved real financial results—not a guess—would be needed.')
        for key in ('Profitability', 'Cash generation', 'Earnings consistency', 'Balance sheet'):
            rating = ratings.get(key)
            if rating is not None and rating < 3:
                goals.append(f'**{key} is only {rating}/5.** The BUY screen requires '
                             'this measure to be at least 3/5 when available. '
                             'Review the category explanation and underlying SEC figures.')
    if missing:
        names = ', '.join(missing)
        goals.append(f'**Still unmeasured:** {names}. A missing category is not a zero or '
                     'a failing grade, but it means the overall business average is based on '
                     'an incomplete picture. Better source coverage would improve confidence.')
    for warning in report.warnings:
        l = warning.lower()
        if 'flagged' in l:
            goals.append('Review the flagged financial years against company filings before '
                         'trusting the growth rates. A BUY requires no flagged revenue observations.')
        if 'stale' in l:
            goals.append('The annual financial statements appear too old relative to the price; '
                         'confirm a newer filed annual report before relying on the screen.')
        if 'not suitable' in l:
            goals.append('This particular scoring model is not designed for banks, insurers, '
                         'financial firms, or REITs. Use an industry-appropriate model instead.')
    if not goals:
        goals.append('The current scores do not clear every BUY condition. Start by reviewing '
                     'valuation and any missing information in the scorecard.')
    return tuple(goals)
